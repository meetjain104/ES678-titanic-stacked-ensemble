# --- 8A. Statistical Significance (McNemar's Exact Test & 95% Bootstrap CI) ---
print("\n--- 8A. STATISTICAL SIGNIFICANCE & BOOTSTRAP 95% CI ---")

def mcnemar_exact_test(y_true, pred_a, pred_b):
    correct_a = (pred_a == y_true)
    correct_b = (pred_b == y_true)
    n01 = int(np.sum((~correct_a) & correct_b))  # A wrong, B right
    n10 = int(np.sum(correct_a & (~correct_b)))  # A right, B wrong
    n_disc = n01 + n10
    p_val = binomtest(min(n01, n10), n=n_disc, p=0.5, alternative='two-sided').pvalue if n_disc > 0 else 1.0
    return n01, n10, p_val

def bootstrap_ci(y_true, preds, n_boot=2000, seed=SEED):
    rng = np.random.default_rng(seed)
    accs = []
    n = len(y_true)
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        accs.append(accuracy_score(y_true[idx], preds[idx]))
    return np.mean(accs), np.percentile(accs, 2.5), np.percentile(accs, 97.5)

