class TitanicPreprocessor(BaseEstimator, TransformerMixin):
    """
    Custom scikit-learn transformer that learns all imputation statistics
    (Age medians, Fare medians, Embarked mode, Ticket frequency) ONLY from the
    training fold during fit(), completely preventing data leakage.
    """
    def __init__(self):
        self.age_medians_ = None
        self.global_age_median_ = None
        self.fare_medians_ = None
        self.global_fare_median_ = None
        self.embarked_mode_ = None
        self.ticket_counts_ = None
        self.feature_columns_ = None

    def _extract_raw_features(self, df):
        data = df.copy()

        # 1. Custom Engineered Variable: Title
        data['Title'] = data['Name'].str.extract(r' ([A-Za-z]+)\.', expand=False).fillna('Rare')
        rare_titles = [
            'Lady', 'Countess', 'Capt', 'Col', 'Don', 'Dr', 'Major',
            'Rev', 'Sir', 'Jonkheer', 'Dona'
        ]
        data['Title'] = data['Title'].replace(rare_titles, 'Rare')
        data['Title'] = data['Title'].replace({'Mlle': 'Miss', 'Ms': 'Miss', 'Mme': 'Mrs'})

        # 2. Custom Engineered Variable: FamilySize & IsAlone
        data['FamilySize'] = data['SibSp'] + data['Parch'] + 1
        data['IsAlone'] = (data['FamilySize'] == 1).astype(int)

        # 3. Cabin Presence & Deck
        data['HasCabin'] = data['Cabin'].notnull().astype(int)
        data['Deck'] = data['Cabin'].fillna('Unknown').str[0]

        # 4. Encode Sex
        data['Sex'] = data['Sex'].map({'male': 0, 'female': 1})

        return data

    def fit(self, X, y=None):
        data = self._extract_raw_features(X)

        # Learn imputation statistics ONLY from training fold
        self.global_age_median_ = data['Age'].median()
        self.age_medians_ = data.groupby(['Title', 'Pclass'])['Age'].median()
        self.global_fare_median_ = data['Fare'].median()
        self.fare_medians_ = data.groupby('Pclass')['Fare'].median()
        emb_mode = data['Embarked'].mode()
        self.embarked_mode_ = emb_mode.iloc[0] if len(emb_mode) > 0 else 'S'
        self.ticket_counts_ = data['Ticket'].value_counts()

        transformed = self._apply_transforms(data)
        self.feature_columns_ = transformed.columns.tolist()
        return self

    def _apply_transforms(self, data):
        # Impute Embarked
        data['Embarked'] = data['Embarked'].fillna(self.embarked_mode_)

        # Impute Fare by Pclass with NaN-safe global fallback
        def impute_fare(row):
            if pd.notnull(row['Fare']):
                return row['Fare']
            val = self.fare_medians_.get(row['Pclass'], self.global_fare_median_)
            return self.global_fare_median_ if pd.isnull(val) else val

        data['Fare'] = data.apply(impute_fare, axis=1).fillna(self.global_fare_median_)

        # Impute Age by (Title, Pclass) with NaN-safe global fallback
        def impute_age(row):
            if pd.notnull(row['Age']):
                return row['Age']
            val = self.age_medians_.get((row['Title'], row['Pclass']), self.global_age_median_)
            return self.global_age_median_ if pd.isnull(val) else val

        data['Age'] = data.apply(impute_age, axis=1).fillna(self.global_age_median_)

        # Engineered Ticket Group Size & Fare Per Person
        data['TicketGroupSize'] = data['Ticket'].map(self.ticket_counts_).fillna(1)
        data['FarePerPerson'] = data['Fare'] / np.maximum(data['FamilySize'], 1)
        data['LogFare'] = np.log1p(data['Fare'])

        # Drop raw IDs/text (PassengerId, Name, Ticket, Cabin)
        keep_cols = [
            'Pclass', 'Sex', 'Age', 'SibSp', 'Parch', 'LogFare',
            'FarePerPerson', 'FamilySize', 'IsAlone', 'HasCabin',
            'TicketGroupSize', 'Embarked', 'Title', 'Deck'
        ]
        model_df = data[keep_cols]

        # One-hot encode categoricals
        model_df = pd.get_dummies(model_df, columns=['Embarked', 'Title', 'Deck'], drop_first=False, dtype=int)
        return model_df

    def transform(self, X):
        data = self._extract_raw_features(X)
        transformed = self._apply_transforms(data)
        # Align columns strictly to training fold schema
        return transformed.reindex(columns=self.feature_columns_, fill_value=0)



